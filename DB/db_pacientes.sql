	CONSTRAINT paciente_pkey PRIMARY KEY (id_paciente),
	CONSTRAINT paciente_id_recepcionista_fkey FOREIGN KEY (id_recepcionista) REFERENCES recepcionista(id_recepcionista) DEFERRABLE,
	CONSTRAINT paciente_id_seguro_fkey FOREIGN KEY (id_seguro) REFERENCES seguro_medico(id_seguro) DEFERRABLE
