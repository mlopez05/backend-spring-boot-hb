CREATE TABLE cita (
	id_cita int4 NOT NULL GENERATED BY DEFAULT AS IDENTITY( INCREMENT BY 1 MINVALUE 1 MAXVALUE 2147483647 START 1 CACHE 1 NO CYCLE),
	id_paciente int4 NOT NULL,
	id_medico int4 NOT NULL,
	id_recepcionista int4 NOT NULL,
	fecha_cita date NOT NULL,
	hora_cita time NOT NULL,
	ubicacion varchar(150) NULL,
	estado varchar(20) NOT NULL DEFAULT 'PENDIENTE'::character varying,
	observaciones varchar(500) NULL,
	fecha_creacion timestamp NOT NULL DEFAULT now(),
	CONSTRAINT chk_estado_cita CHECK (((estado)::text = ANY ((ARRAY['PENDIENTE'::character varying, 'CONFIRMADA'::character varying, 'CANCELADA'::character varying, 'COMPLETADA'::character varying])::text[]))),
	CONSTRAINT cita_pkey PRIMARY KEY (id_cita),
	CONSTRAINT cita_id_medico_fkey FOREIGN KEY (id_medico) REFERENCES medico(id_medico) DEFERRABLE,
	CONSTRAINT cita_id_paciente_fkey FOREIGN KEY (id_paciente) REFERENCES paciente(id_paciente) DEFERRABLE,
	CONSTRAINT cita_id_recepcionista_fkey FOREIGN KEY (id_recepcionista) REFERENCES recepcionista(id_recepcionista) DEFERRABLE
);
CREATE INDEX idx_cita_fecha ON public.cita USING btree (fecha_cita);
CREATE INDEX idx_cita_medico ON public.cita USING btree (id_medico);
CREATE INDEX idx_cita_paciente ON public.cita USING btree (id_paciente);